// Generates supabase/migrations/20260901000000_baseline_tables.sql from the
// production column export (supabase/baseline/source/production_columns.csv).
//
// Deterministic and re-runnable: `node supabase/baseline/generate-baseline-tables.mjs`
// Only STRUCTURE facts present in the export are emitted (columns, types,
// NOT NULL, defaults). Constraints, RLS, policies, functions, triggers,
// indexes, storage and cron come from the definitions export — see
// supabase/baseline/README.md and generate-baseline-logic.mjs.

import fs from 'node:fs';
import path from 'node:path';
import { parseCsvObjects } from './csv.mjs';

const root = process.cwd();
const src = path.join(root, 'supabase/baseline/source/production_columns.csv');
// BASELINE_TABLES_OUT is a test-only override (drift detection in scripts/audit-baseline.mjs).
const out = process.env.BASELINE_TABLES_OUT
  ? path.resolve(process.env.BASELINE_TABLES_OUT)
  : path.join(root, 'supabase/migrations/20260901000000_baseline_tables.sql');

const rows = parseCsvObjects(fs.readFileSync(src, 'utf8'));

function sqlType(r) {
  if (r.data_type === 'ARRAY') return r.udt_name.replace(/^_/, '') + '[]';
  if (r.data_type === 'timestamp with time zone') return 'timestamptz';
  return r.data_type;
}

// Columns whose Postgres identity/serial nature is invisible in
// information_schema.columns (column_default is NULL for identity columns).
// Confirmed/adjusted by the definitions export (attidentity) in the logic file.
const IDENTITY = new Set(['product_events.id']);

const tables = new Map();
for (const r of rows) {
  if (!tables.has(r.table_name)) tables.set(r.table_name, []);
  tables.get(r.table_name).push(r);
}

const lines = [];
lines.push(`-- BASELINE (DEV BOOTSTRAP ONLY): FairPath production table structure.
--
-- Generated from a read-only export of the production 'fairpath-mobile'
-- project's public schema (36 tables, ${rows.length} columns) by
-- supabase/baseline/generate-baseline-tables.mjs. DO NOT hand-edit —
-- regenerate instead.
--
-- Contains ONLY: table + column definitions, types, NOT NULL, defaults.
-- Primary/foreign/unique/check constraints, indexes, RLS, policies,
-- functions, triggers, grants, storage buckets and cron come from the
-- production definitions export via
-- supabase/migrations/20260901000100_baseline_constraints_security_logic.sql.
--
-- SAFETY GUARD: this migration REFUSES to run if public.profiles already
-- exists. Production has public.profiles, so this file can never be applied
-- to production (or to any already-bootstrapped database) — it can only
-- bootstrap an EMPTY database such as fairpath-mobile-dev.
--
-- Never mark this migration as applied on production (no 'migration repair'
-- against production).

do $$
begin
  if to_regclass('public.profiles') is not null then
    raise exception 'BASELINE REFUSED: public.profiles already exists. This baseline only bootstraps an empty database (fairpath-mobile-dev). It must never run against production.';
  end if;
end $$;
`);

for (const [table, cols] of tables) {
  lines.push(`create table public."${table}" (`);
  const defs = cols.map((c) => {
    let d = `  "${c.column_name}" ${sqlType(c)}`;
    const key = `${table}.${c.column_name}`;
    if (IDENTITY.has(key)) d += ' generated by default as identity';
    else if (c.column_default && c.column_default !== 'null') d += ` default ${c.column_default}`;
    if (c.is_nullable === 'NO') d += ' not null';
    return d;
  });
  lines.push(defs.join(',\n'));
  lines.push(');\n');
}

fs.writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${path.relative(root, out)}: ${tables.size} tables, ${rows.length} columns.`);
