CREATE OR REPLACE FUNCTION public.approve_marketplace_claim(p_claim_id uuid)
 RETURNS TABLE(id uuid, status text, pickup_deadline timestamp with time zone, pickup_code text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
 v_user uuid:=auth.uid();
 v_item uuid;
 v_claimant uuid;
 v_code text:=upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));
 v_deadline timestamptz:=now()+interval '48 hours';
begin
 if v_user is null then raise exception 'SIGNED_OUT'; end if;
 select c.item_id,c.claimant_id into v_item,v_claimant
 from public.marketplace_claims c join public.marketplace_items i on i.id=c.item_id
 where c.id=p_claim_id and c.status='requested' and i.seller_id=v_user and i.status='available'
 for update of c,i;
 if v_item is null then raise exception 'CLAIM_NOT_APPROVABLE'; end if;

 update public.marketplace_claims c
 set status='approved',approved_at=now(),pickup_deadline=v_deadline,pickup_code=v_code,updated_at=now()
 where c.id=p_claim_id;

 update public.marketplace_claims c
 set status='declined',declined_at=now(),counts_toward_quota=false,updated_at=now()
 where c.item_id=v_item and c.id<>p_claim_id and c.status='requested';

 update public.marketplace_items i set status='pending_pickup',updated_at=now() where i.id=v_item;

 insert into public.marketplace_claim_events(claim_id,actor_user_id,event_type,metadata)
 values(p_claim_id,v_user,'approved',jsonb_build_object('pickup_deadline',v_deadline));

 insert into public.user_notifications(user_id,category,title,body,route,metadata)
 values(v_claimant,'marketplace_claim','Marketplace claim approved','You have 48 hours to pick up your item. Open your claim for private pickup details and verification code.','/marketplace-claim/'||p_claim_id,jsonb_build_object('claim_id',p_claim_id,'item_id',v_item));

 insert into public.user_notifications(user_id,category,title,body,route,metadata)
 select c.claimant_id,'marketplace_claim','Marketplace claim update','Another claimant was selected for this item. This declined request does not count against your monthly claim limit.','/marketplace-claim/'||c.id,jsonb_build_object('claim_id',c.id,'item_id',v_item)
 from public.marketplace_claims c where c.item_id=v_item and c.status='declined' and c.declined_at>=now()-interval '5 seconds';

 return query select c.id,c.status,c.pickup_deadline,c.pickup_code from public.marketplace_claims c where c.id=p_claim_id;
end; $function$;
revoke all on function public.approve_marketplace_claim(uuid) from public, anon, authenticated, service_role;
grant execute on function public.approve_marketplace_claim(uuid) to authenticated, service_role;

