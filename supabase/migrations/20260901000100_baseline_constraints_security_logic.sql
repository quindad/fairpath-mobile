CREATE OR REPLACE FUNCTION public.request_marketplace_claim(p_item_id uuid, p_message text DEFAULT NULL::text)
 RETURNS TABLE(id uuid, status text, created_at timestamp with time zone)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
 v_user uuid:=auth.uid();
 v_seller uuid;
 v_status text;
 v_moderation text;
 v_limit integer:=1;
 v_used integer:=0;
 v_existing public.marketplace_claims%rowtype;
 v_created public.marketplace_claims%rowtype;
 v_has_existing boolean:=false;
begin
 if v_user is null then raise exception 'SIGNED_OUT'; end if;

 select i.seller_id,i.status,i.moderation_status into v_seller,v_status,v_moderation
 from public.marketplace_items i where i.id=p_item_id;

 if v_seller is null then raise exception 'ITEM_NOT_FOUND'; end if;
 if v_seller=v_user then raise exception 'OWN_ITEM'; end if;
 if v_status<>'available' or v_moderation<>'approved' then raise exception 'ITEM_UNAVAILABLE'; end if;

 select * into v_existing from public.marketplace_claims c
 where c.item_id=p_item_id and c.claimant_id=v_user;
 v_has_existing:=found;

 if v_has_existing and v_existing.status in ('requested','approved','ready','picked_up','no_show') then
   return query select v_existing.id,v_existing.status,v_existing.created_at;
   return;
 end if;

 if exists(
  select 1 from public.fairpath_subscriptions s
  where s.user_id=v_user and s.plan='fairpath_plus' and s.status='active'
    and (s.current_period_end is null or s.current_period_end>now())
 ) then v_limit:=7; end if;

 select count(*) into v_used
 from public.marketplace_claims c
 where c.claimant_id=v_user
   and c.created_at>=date_trunc('month',now())
   and c.created_at<date_trunc('month',now())+interval '1 month'
   and c.counts_toward_quota;

 if v_used>=v_limit then raise exception 'CLAIM_LIMIT_REACHED'; end if;

 if v_has_existing then
   update public.marketplace_claims c set
     status='requested',counts_toward_quota=true,pickup_deadline=null,pickup_code=null,
     approved_at=null,ready_at=null,completed_at=null,cancelled_at=null,declined_at=null,no_show_at=null,
     created_at=now(),updated_at=now()
   where c.id=v_existing.id
   returning * into v_created;
 else
   insert into public.marketplace_claims(item_id,claimant_id,status,counts_toward_quota,updated_at)
   values(p_item_id,v_user,'requested',true,now())
   returning * into v_created;
 end if;

 insert into public.marketplace_claim_events(claim_id,actor_user_id,event_type)
 values(v_created.id,v_user,'requested');

 insert into public.user_notifications(user_id,category,title,body,route,metadata)
 values(v_seller,'marketplace_claim','New Marketplace claim request',
   'Someone requested your free Marketplace item. Claimants stay anonymous while you choose.',
   '/marketplace-manage/'||p_item_id,
   jsonb_build_object('item_id',p_item_id,'claim_id',v_created.id));

 return query select v_created.id,v_created.status,v_created.created_at;
end;
$function$;
revoke all on function public.request_marketplace_claim(uuid,text) from public, anon, authenticated, service_role;
grant execute on function public.request_marketplace_claim(uuid,text) to authenticated, service_role;

