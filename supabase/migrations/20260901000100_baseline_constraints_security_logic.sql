CREATE OR REPLACE FUNCTION public.submit_housing_application(p_application_id uuid, p_answers jsonb, p_consent jsonb)
 RETURNS TABLE(id uuid, status text, submitted_at timestamp with time zone)
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_user uuid := auth.uid();
  v_now timestamptz := now();
  v_type text;
  v_listing_id uuid;
  v_required_docs text[] := '{}';
  v_required_doc text;
  v_enforced boolean := false;
  v_payment text;
  v_phone text;
  v_occupants integer;
  v_income numeric;
begin
  if v_user is null then raise exception 'SIGNED_OUT'; end if;
  if coalesce((p_consent->>'accuracy')::boolean,false) is not true
     or coalesce((p_consent->>'submit')::boolean,false) is not true then
    raise exception 'CONSENT_REQUIRED';
  end if;

  select a.application_type,a.listing_id,l.required_application_documents
    into v_type,v_listing_id,v_required_docs
  from public.housing_applications a
  join public.housing_listings l on l.id=a.listing_id
  where a.id=p_application_id
    and a.user_id=v_user
    and a.status='started';

  if v_type is null then raise exception 'APPLICATION_NOT_SUBMITTABLE'; end if;
  if v_type='fasttrack' and coalesce((p_consent->>'fasttrack_ack')::boolean,false) is not true then
    raise exception 'FASTTRACK_ACK_REQUIRED';
  end if;

  -- Server-side required-answer enforcement; client validation is not trusted as the only gate.
  if length(trim(coalesce(p_answers->>'first_name','')))<2
     or length(trim(coalesce(p_answers->>'last_name','')))<2
     or trim(coalesce(p_answers->>'email','')) !~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
     or trim(coalesce(p_answers->>'current_address',''))=''
     or trim(coalesce(p_answers->>'employment_status',''))=''
     or trim(coalesce(p_answers->>'move_in_date','')) !~ '^[0-9]{2}/[0-9]{2}/[0-9]{4}$'
     or trim(coalesce(p_answers->>'date_of_birth','')) !~ '^[0-9]{2}/[0-9]{2}/[0-9]{4}$'
     or trim(coalesce(p_answers->>'pets',''))=''
     or trim(coalesce(p_answers->>'housing_history',''))=''
     or trim(coalesce(p_answers->>'references',''))='' then
    raise exception 'APPLICATION_INCOMPLETE';
  end if;

  v_phone := regexp_replace(coalesce(p_answers->>'phone',''),'[^0-9]','','g');
  if length(v_phone)<>10 then raise exception 'APPLICATION_INCOMPLETE'; end if;

  begin
    v_occupants := (p_answers->>'occupants')::integer;
  exception when others then
    raise exception 'APPLICATION_INCOMPLETE';
  end;
  if v_occupants<1 then raise exception 'APPLICATION_INCOMPLETE'; end if;

  begin
    v_income := regexp_replace(coalesce(p_answers->>'monthly_income',''),'[^0-9.]','','g')::numeric;
  exception when others then
    raise exception 'APPLICATION_INCOMPLETE';
  end;
  if v_income<0 then raise exception 'APPLICATION_INCOMPLETE'; end if;

  if p_answers->>'employment_status'<>'Unemployed' and trim(coalesce(p_answers->>'employer',''))='' then
    raise exception 'APPLICATION_INCOMPLETE';
  end if;

  foreach v_required_doc in array coalesce(v_required_docs,'{}'::text[]) loop
    if not exists(
      select 1 from public.housing_application_documents d
      where d.application_id=p_application_id
        and d.user_id=v_user
        and d.document_type=v_required_doc
        and d.status<>'rejected'
    ) then
      raise exception 'REQUIRED_DOCUMENTS_MISSING';
    end if;
  end loop;

  if v_type='fasttrack' then
    select coalesce((c.value #>> '{}')::boolean,false)
      into v_enforced
    from public.app_config c
    where c.key='fasttrack_payment_enforced';

    if v_enforced then
      select o.status into v_payment
      from public.housing_fasttrack_orders o
      where o.application_id=p_application_id and o.user_id=v_user;

      if coalesce(v_payment,'') not in ('paid','waived') then raise exception 'PAYMENT_REQUIRED'; end if;
    end if;
  end if;

  update public.housing_applications a
  set answers=p_answers,
      current_step=5,
      status='submitted',
      submitted_at=v_now,
      updated_at=v_now,
      applicant_snapshot=p_answers,
      consent_snapshot=p_consent||jsonb_build_object('confirmed_at',v_now)
  where a.id=p_application_id
    and a.user_id=v_user
    and a.status='started';

  if not found then raise exception 'APPLICATION_NOT_SUBMITTABLE'; end if;

  return query
  select a.id,a.status,a.submitted_at
  from public.housing_applications a
  where a.id=p_application_id and a.user_id=v_user;
end;
$function$;
revoke all on function public.submit_housing_application(uuid,jsonb,jsonb) from public, anon, authenticated, service_role;
grant execute on function public.submit_housing_application(uuid,jsonb,jsonb) to public, anon, authenticated, service_role;

