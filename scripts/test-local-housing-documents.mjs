import { createLocalDb, addUser, tryAs } from './lib/local-db.mjs';
import assert from 'node:assert/strict';
const { db, errors } = await createLocalDb();
assert.equal(errors.length, 0);
const user = await addUser(db, 'housing-doc-qa@test.local');
const listing = (await db.query(`insert into public.housing_listings(owner_id,title,description,property_type,city,state,postal_code,rent_monthly,status,required_application_documents) values($1,'Synthetic document gate','Synthetic','apartment','Cleveland','OH','44113',1000,'published',array['identity']) returning id`, [user])).rows[0].id;
const app = (await db.query(`insert into public.housing_applications(user_id,listing_id) values($1,$2) returning id`, [user, listing])).rows[0].id;
const answers = { first_name: 'Synthetic', last_name: 'Member', email: 'qa@example.com', current_address: 'Synthetic address', employment_status: 'Unemployed', move_in_date: '12/01/2026', date_of_birth: '01/01/1990', pets: 'None', housing_history: 'No history', references: 'None', phone: '2165550100', occupants: '1', monthly_income: '0' };
const submit = () => tryAs(db, user, 'select * from public.submit_housing_application($1,$2,$3)', [app, answers, { accuracy: true, submit: true }]);
assert.match((await submit()).error, /REQUIRED_DOCUMENTS_MISSING/);
console.log('PASS required document missing rejects submission');
const path = `${user}/${app}/synthetic.pdf`;
await db.query(`insert into public.housing_application_documents(application_id,user_id,document_type,file_name,storage_path) values($1,$2,'identity','synthetic.pdf',$3)`, [app, user, path]);
assert.match((await submit()).error, /REQUIRED_DOCUMENTS_MISSING/);
console.log('PASS a document row alone cannot bypass the Storage gate');
await db.query(`insert into storage.objects(bucket_id,name) values('housing-application-documents',$1)`, [path]);
const result = await submit();
assert.equal(result.error, undefined);
assert.equal((await db.query('select status from public.housing_applications where id=$1', [app])).rows[0].status, 'submitted');
console.log('PASS matching document and Storage metadata permit submission (local SQL proof; no physical file assertion)');
await db.close();
